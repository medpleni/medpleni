export const SUBSPECIALTIES_BY_AREA: Record<string, string[]> = (() => {
  const map: Record<string, Set<string>> = {};
  MED_CLASSES_CATALOG.forEach((item) => {
    if (!map[item.area]) {
      map[item.area] = new Set();
    }
    map[item.area].add(item.discipline);
  });
  const result: Record<string, string[]> = {};
  for (const [k, v] of Object.entries(map)) {
    result[k] = Array.from(v).sort();
  }
  return result;
})();

export function getClassById(id: string): ClassItem | undefined {
  const found = ALL_CLASSES_CATALOG.find((c) => c.id === id || String(c.index) === id);
  return found;
}

export function getAdjacentClasses(id: string): {
  prev: ClassItem | null;
  next: ClassItem | null;
} {
  const idx = ALL_CLASSES_CATALOG.findIndex((c) => c.id === id || String(c.index) === id);
  if (idx === -1) {
    return { prev: null, next: null };
  }
  return {
    prev: idx > 0 ? ALL_CLASSES_CATALOG[idx - 1] : null,
    next: idx < ALL_CLASSES_CATALOG.length - 1 ? ALL_CLASSES_CATALOG[idx + 1] : null,
  };
}
